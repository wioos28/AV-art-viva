export type I18nKey = keyof typeof DICT.vi;

/** Lấy chuỗi dịch theo key (locale do settings quyết định). */
export function t(key: I18nKey, locale: Locale): string {
  const table = DICT[locale] ?? DICT.vi;
  return (table as Record<string, string>)[key] ?? DICT.vi[key] ?? key;
}

/** Hàm dịch có chèn tham số: t('elementsCount', {n: 5}). */
export function tf(key: I18nKey, locale: Locale, params: Record<string, string | number>): string {
  let s = t(key, locale);
  for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}
